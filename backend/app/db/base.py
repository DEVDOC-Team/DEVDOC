"""SQLAlchemy declarative base and shared column mixins.

All DEVDOC models inherit from ``Base``.
Common behaviour (UUID primary key, UTC timestamps) lives in mixins so
it stays DRY and easy to audit.
"""

from __future__ import annotations

import uuid
from datetime import UTC, datetime

from sqlalchemy import DateTime, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


def _utcnow() -> datetime:
    """Return the current moment in UTC (timezone-aware)."""
    return datetime.now(UTC)


class Base(DeclarativeBase):
    """Shared declarative base for all DEVDOC models."""


class UUIDMixin:
    """UUID primary key generated by the database (PostgreSQL gen_random_uuid).

    Falls back to Python uuid4 for SQLite (used in unit tests).
    """

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        default=uuid.uuid4,
        # server_default is set per-dialect in session.py via event listeners
        # so we keep the Python fallback here for portability.
    )


class TimestampMixin:
    """Automatic UTC created_at / updated_at columns.

    * created_at — set once on INSERT, never changed.
    * updated_at — updated on every UPDATE by the database (server_onupdate).
    """

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=_utcnow,
        server_default=func.now(),
    )

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=_utcnow,
        server_default=func.now(),
        onupdate=_utcnow,
        server_onupdate=func.now(),  # type: ignore[arg-type]
    )
