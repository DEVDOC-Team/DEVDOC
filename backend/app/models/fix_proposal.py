"""FixProposal model.

A FixProposal is a concrete code change or configuration correction
generated by the DEVDOC AI agent as a candidate solution for an
Investigation.

Before any proposal reaches production it must:
1. Pass sandbox verification (automated tests in isolated environment).
2. Receive human approval recorded in the Approval model.

Lifecycle
---------
DRAFT → SANDBOX_PENDING → SANDBOX_RUNNING → SANDBOX_PASSED
                                          → SANDBOX_FAILED
SANDBOX_PASSED → AWAITING_APPROVAL → APPROVED → APPLIED
                                   → REJECTED
"""

from __future__ import annotations

import enum
import uuid

from sqlalchemy import Enum as SAEnum
from sqlalchemy import ForeignKey, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base, TimestampMixin, UUIDMixin


class FixStatus(str, enum.Enum):
    DRAFT = "draft"
    SANDBOX_PENDING = "sandbox_pending"
    SANDBOX_RUNNING = "sandbox_running"
    SANDBOX_PASSED = "sandbox_passed"
    SANDBOX_FAILED = "sandbox_failed"
    AWAITING_APPROVAL = "awaiting_approval"
    APPROVED = "approved"
    REJECTED = "rejected"
    APPLIED = "applied"
    REVERTED = "reverted"


class FixProposal(UUIDMixin, TimestampMixin, Base):
    __tablename__ = "fix_proposals"

    investigation_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("investigations.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    title: Mapped[str] = mapped_column(String(512), nullable=False)
    description: Mapped[str | None] = mapped_column(Text, nullable=True)

    # The actual diff or patch generated by the AI
    patch_content: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Files that the patch targets
    affected_files: Mapped[str | None] = mapped_column(Text, nullable=True)

    status: Mapped[FixStatus] = mapped_column(
        SAEnum(FixStatus, name="fixstatus"),
        nullable=False,
        default=FixStatus.DRAFT,
        index=True,
    )

    # Sandbox run details
    sandbox_run_id: Mapped[str | None] = mapped_column(String(256), nullable=True)
    sandbox_log: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Confidence score from AI (0-100)
    confidence_score: Mapped[int | None] = mapped_column(nullable=True)

    # ------------------------------------------------------------------ #
    # Relationships
    # ------------------------------------------------------------------ #
    investigation: Mapped[Investigation] = relationship(  # type: ignore[name-defined]
        "Investigation", back_populates="fix_proposals"
    )
    approvals: Mapped[list[Approval]] = relationship(  # type: ignore[name-defined]
        "Approval", back_populates="fix_proposal", cascade="all, delete-orphan"
    )

    def __repr__(self) -> str:
        return f"<FixProposal id={self.id!s:.8} status={self.status}>"
